/**
 * Written-up movements.
 *
 * What a member gets when they tap a line in a workout: the movement's proper
 * name in both languages, a few cues, and the one thing to watch. Cues are
 * technique, never load - what somebody lifts is theirs to decide on the day,
 * the same rule the workout library itself is written under.
 *
 * `en` is the name a demonstration is searched under, so it is the name the
 * field actually uses: English for barbell and gymnastics work, Sanskrit for
 * asanas, the Pilates name for Pilates. `aliases` carries the other ways the
 * library happens to write it.
 *
 * Nothing here rates a body, compares one member to another, or mentions
 * weight loss. A movement is described by what it does, not by what it is
 * supposed to make someone look like.
 */
export interface MovementGuide {
  id: string;
  /** Canonical Hebrew name. */
  he: string;
  /** Canonical name in the language the movement is taught in. */
  en: string;
  /** Two to four short cues, in order of execution. */
  cues: string[];
  /** The one mistake worth naming. Optional. */
  watch?: string;
  /** Other spellings the library uses. */
  aliases?: string[];
}

